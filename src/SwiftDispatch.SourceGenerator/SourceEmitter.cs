using System.Collections.Generic;
using System.Text;

namespace SwiftDispatch.SourceGenerator;

internal static class SourceEmitter
{
    internal static IEnumerable<GeneratedSource> Emit(DispatchModel model)
    {
        var registration = CreateFile();
        RegistrationEmitter.Emit(registration, model);
        yield return CompleteFile("SwiftDispatch.Registration.g.cs", registration);

        var table = CreateFile();
        DispatchTableEmitter.Emit(table, model);
        yield return CompleteFile("SwiftDispatch.DispatchTable.g.cs", table);

        for (int index = 0; index < model.Requests.Count; index++)
        {
            var dispatcher = CreateFile();
            RequestDispatchModel request = model.Requests[index];
            RequestEmitter.Emit(dispatcher, request, index);
            string kind = request.Streams ? "Stream" : "Request";
            yield return CompleteFile($"SwiftDispatch.{kind}.{index}.g.cs", dispatcher);
        }

        for (int index = 0; index < model.Notifications.Count; index++)
        {
            var dispatcher = CreateFile();
            NotificationEmitter.Emit(dispatcher, model.Notifications[index], index);
            yield return CompleteFile($"SwiftDispatch.Notification.{index}.g.cs", dispatcher);
        }
    }

    private static StringBuilder CreateFile()
    {
        var code = new StringBuilder();
        code.AppendLine("""
            // <auto-generated/>
            #nullable enable
            namespace Microsoft.Extensions.DependencyInjection;
            internal static partial class SwiftDispatchGeneratedServiceCollectionExtensions
            {
            """);
        return code;
    }

    private static GeneratedSource CompleteFile(string hintName, StringBuilder code) =>
        new(hintName, code.AppendLine("}").ToString());
}

internal sealed class GeneratedSource(string hintName, string text)
{
    public string HintName { get; } = hintName;
    public string Text { get; } = text;
}
