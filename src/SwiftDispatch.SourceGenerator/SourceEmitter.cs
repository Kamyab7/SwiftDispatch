using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;
using static SwiftDispatch.SourceGenerator.SymbolHelpers;

namespace SwiftDispatch.SourceGenerator;

internal static class SourceEmitter
{
    internal static string Emit(List<Request> requests, List<Observer> notifications,
        Dictionary<INamedTypeSymbol, IMethodSymbol> constructors, INamedTypeSymbol? notificationStrategy)
    {
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        RegistrationEmitter.Emit(code, constructors, notificationStrategy);
        DispatchTableEmitter.Emit(code, requests, notifications);
        RequestEmitter.Emit(code, requests);
        NotificationEmitter.Emit(code, notifications);
        return code.AppendLine("}").ToString();
    }

    internal static string Resolve(ITypeSymbol type)
    {
        const string resolver = "global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService";
        if (type.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
        {
            return "(" + Name(type) + ")" + resolver + "(sp, typeof(" + Name(type) + "))";
        }
        return resolver + "<" + Name(type.WithNullableAnnotation(NullableAnnotation.NotAnnotated)) + ">(sp)";
    }
}
