using System.Text;

namespace SwiftDispatch.SourceGenerator;

internal static class SourceEmitter
{
    internal static string Emit(DispatchModel model)
    {
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        RegistrationEmitter.Emit(code, model);
        DispatchTableEmitter.Emit(code, model);
        RequestEmitter.Emit(code, model.Requests);
        NotificationEmitter.Emit(code, model.Notifications);
        return code.AppendLine("}").ToString();
    }
}
